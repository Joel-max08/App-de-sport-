/* Kinetra — langues : français (par défaut), anglais, allemand.
   Les textes sont reconnus par leur version française (clé) ; le moteur remplace le texte affiché
   à chaque changement du DOM (MutationObserver), donc aussi les textes générés par le JavaScript. */
(function(){
'use strict';
const LANG_KEY='sportapp.lang';
const LANGS=['fr','en','de'];
let LANG='fr';
try{
  const saved=localStorage.getItem(LANG_KEY);
  if(saved&&LANGS.includes(saved))LANG=saved;
  else{const nav=(navigator.language||'fr').slice(0,2).toLowerCase();if(LANGS.includes(nav))LANG=nav}
}catch(e){}

// Phrases avec des nombres : modèles reconnus par expression régulière
const PATTERNS=[
[/^(\d+) exercice\(s\) avec ton matériel, (\d+) au poids du corps\.$/, m=>({en:`${m[1]} exercise(s) with your equipment, ${m[2]} bodyweight.`,de:`${m[1]} Übung(en) mit deinem Equipment, ${m[2]} mit Körpergewicht.`})],
[/^Bonjour, (.+) !$/, m=>({en:'Hello, '+m[1]+'!',de:'Hallo, '+m[1]+'!'})],
[/^Synchronisé à (.+)$/, m=>({en:'Synced at '+m[1],de:'Synchronisiert um '+m[1]})],
[/^Pour (\d+) portions?$/, m=>({en:'For '+m[1]+(m[1]==='1'?' serving':' servings'),de:'Für '+m[1]+(m[1]==='1'?' Portion':' Portionen')})],
[/^(\d+) séances? par semaine$/, m=>({en:m[1]+(m[1]==='1'?' workout':' workouts')+' per week',de:m[1]+(m[1]==='1'?' Training':' Trainings')+' pro Woche'})],
  [/^(\d+) semaines? de suite$/,m=>({en:`${m[1]} week${m[1]==='1'?'':'s'} in a row`,de:`${m[1]} Woche${m[1]==='1'?'':'n'} in Folge`})],
  [/^(\d+) verres? sur 8 · environ ([\d.,]+) L$/,m=>({en:`${m[1]} of 8 glasses · about ${m[2]} L`,de:`${m[1]} von 8 Gläsern · etwa ${m[2]} L`})],
  [/^(\d+) exercices? · environ (\d+) min$/,m=>({en:`${m[1]} exercise${m[1]==='1'?'':'s'} · about ${m[2]} min`,de:`${m[1]} Übung${m[1]==='1'?'':'en'} · etwa ${m[2]} Min.`})],
  [/^(\d+) portions? · (\d+) ingrédients?$/,m=>({en:`${m[1]} serving${m[1]==='1'?'':'s'} · ${m[2]} ingredient${m[2]==='1'?'':'s'}`,de:`${m[1]} Portion${m[1]==='1'?'':'en'} · ${m[2]} Zutat${m[2]==='1'?'':'en'}`})],
  [/^(\d+) séances? par semaine$/,m=>({en:`${m[1]} workout${m[1]==='1'?'':'s'} per week`,de:`${m[1]} Einheit${m[1]==='1'?'':'en'} pro Woche`})],
  [/^Fais deux séances du même exercice pour voir ta courbe\.$/,()=>({en:'Do two workouts with the same exercise to see your chart.',de:'Mach zwei Einheiten mit derselben Übung, um deine Kurve zu sehen.'})],
];
function patTranslate(key){
  for(const[re,fn]of PATTERNS){const m=key.match(re);if(m){const r=fn(m);return r[LANG]}}
  return null;
}

function tr(s){
  if(LANG==='fr')return s;
  const e=I18N_DICT[s];
  return(e&&e[LANG])||s;
}
window.tr=tr;
window.getLang=()=>LANG;

const SKIP=/^(SCRIPT|STYLE|TEXTAREA|CODE)$/;
const ATTRS=['placeholder','aria-label'];

function fix(node,v,get,set){
  // node.__last : dernière valeur écrite par le moteur ; node.__fr : texte français d'origine
  if(node.__last!==undefined&&v===node.__last)v=node.__fr;
  else node.__fr=v;
  const base=v;
  const key=base.trim();
  if(!key)return;
  let out=base;
  if(LANG!=='fr'){
    const e=I18N_DICT[key];
    const t=(e&&e[LANG])||patTranslate(key);
    if(t){
      const lead=base.match(/^\s*/)[0],trail=base.match(/\s*$/)[0];
      out=lead+t+trail;
    }
  }
  const cur=get();
  if(out!==cur){set(out);node.__last=out}
  else node.__last=undefined;
}

function walk(root){
  const w=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes=[];let n;
  while((n=w.nextNode()))nodes.push(n);
  for(const node of nodes){
    const p=node.parentNode;
    if(!p||SKIP.test(p.nodeName))continue;
    fix(node,node.nodeValue,()=>node.nodeValue,v=>{node.nodeValue=v});
  }
  root.querySelectorAll('[placeholder],[aria-label]').forEach(el=>{
    ATTRS.forEach(a=>{
      if(!el.hasAttribute(a))return;
      const cur=el.getAttribute(a);
      const k='__'+a;
      let base;
      if(el[k+'Last']!==undefined&&cur===el[k+'Last'])base=el[k+'Fr'];
      else{base=cur;el[k+'Fr']=cur}
      let out=base;
      const e=I18N_DICT[base.trim()];
      if(LANG!=='fr'&&e&&e[LANG])out=e[LANG];
      if(out!==cur){el.setAttribute(a,out);el[k+'Last']=out}
      else el[k+'Last']=undefined;
    });
  });
}

let pending=false;
const mo=new MutationObserver(()=>{
  if(pending)return;
  pending=true;
  requestAnimationFrame(()=>{pending=false;apply()});
});

function apply(){
  document.documentElement.lang=LANG;
  mo.disconnect();
  if(document.body)walk(document.body);
  const s=document.getElementById('lang');if(s)s.value=LANG;
  if(document.body)mo.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:ATTRS});
}

window.setLang=function(v){
  if(!LANGS.includes(v))return;
  LANG=v;
  try{localStorage.setItem(LANG_KEY,v)}catch(e){}
  apply();
  if(typeof window.render==='function')window.render();
};

if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',apply);
else apply();
})();
